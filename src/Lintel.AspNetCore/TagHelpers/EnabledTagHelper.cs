using Microsoft.AspNetCore.Razor.TagHelpers;

namespace Lintel.AspNetCore.TagHelpers;

/// <summary>
/// Disables an element when the condition is false: <c>&lt;a asp-action="Edit" asp-enabled="Model.CanEdit"&gt;</c>.
/// </summary>
/// <remarks>
/// <para>A disabled element gets the class <c>disabled</c> (Bootstrap 5) and:</para>
/// <list type="bullet">
/// <item><c>a</c>: <c>href</c> is removed, <c>aria-disabled="true"</c> and <c>tabindex="-1"</c> are added, so the link
/// neither navigates nor takes focus;</item>
/// <item><c>button</c>, <c>input</c>, <c>select</c>, <c>textarea</c>, <c>fieldset</c>, <c>option</c>, <c>optgroup</c>:
/// the <c>disabled</c> attribute;</item>
/// <item>other elements: <c>aria-disabled="true"</c>.</item>
/// </list>
/// <para>
/// The tag helper runs after the others (<see cref="Order"/> is 1000), so it sees the <c>href</c> generated by
/// <c>asp-action</c> and the final element of tag helpers that replace their tag. Scripts that handle clicks themselves
/// should check <c>aria-disabled</c> or the <c>disabled</c> class.
/// </para>
/// </remarks>
[HtmlTargetElement(Attributes = EnabledAttributeName)]
public class EnabledTagHelper : TagHelper
{
    private const string EnabledAttributeName = "asp-enabled";

    private static readonly HashSet<string> _disableableElements = new(StringComparer.OrdinalIgnoreCase)
    {
        "button", "input", "select", "textarea", "fieldset", "option", "optgroup",
    };

    /// <inheritdoc />
    public override int Order => 1000;

    /// <summary>Whether the element is enabled. Default: <see langword="true"/>.</summary>
    [HtmlAttributeName(EnabledAttributeName)]
    public bool Enabled { get; set; } = true;

    /// <inheritdoc />
    public override void Process(TagHelperContext context, TagHelperOutput output)
    {
        ArgumentNullException.ThrowIfNull(output);

        if (Enabled)
        {
            return;
        }

        output.AddClass("disabled");
        if (string.Equals(output.TagName, "a", StringComparison.OrdinalIgnoreCase))
        {
            output.Attributes.RemoveAll("href");
            output.Attributes.SetAttribute("aria-disabled", "true");
            output.Attributes.SetAttribute("tabindex", "-1");
        }
        else if (output.TagName is not null && _disableableElements.Contains(output.TagName))
        {
            output.Attributes.SetAttribute("disabled", "disabled");
        }
        else
        {
            output.Attributes.SetAttribute("aria-disabled", "true");
        }
    }
}
